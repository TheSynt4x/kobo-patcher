#!/usr/bin/env python3
"""Write patches_data.h, the patch list built into the mod, from patches.yaml and web/patches/."""
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]


def c(text):
    return json.dumps(text)


def main():
    source = yaml.safe_load((ROOT / "patches.yaml").read_text())
    # In the page's order: by category as patches.yaml lists them, then as the patches are listed.
    order = {category: index for index, category in enumerate(source["categories"])}
    patches = sorted(source["patches"], key=lambda patch: order[patch["category"]])
    out = [
        "/* Generated by gen_data.py. Don't edit. */",
        "typedef struct { const char *file; unsigned at; const char *find, *replace; } Edit;",
        "typedef struct { const char *id, *title, *category, *group, *warning; const Edit *edits; int edit_count; } Patch;",
        "typedef struct { const char *model, *name, *version; const Patch *patches; int patch_count; } Firmware;",
    ]
    firmwares = []
    for index, firmware in enumerate(source["firmware"]):
        edits_by_id = json.loads((ROOT / "web/patches" / f"{firmware['model']}-{firmware['firmware']}.json").read_text())
        rows = []
        for number, patch in enumerate(patches):
            edits = edits_by_id.get(patch["id"])
            if not edits:
                continue
            name = f"edits_{index}_{number}"
            out.append(f"static const Edit {name}[] = {{")
            for edit in edits:
                out.append(f"  {{{c(edit['file'].removeprefix('.'))}, {edit['at']}, {c(edit['find'])}, {c(edit['replace'])}}},")
            out.append("};")
            group, warning = patch.get("group"), patch.get("warning")
            rows.append(f"  {{{c(patch['id'])}, {c(patch['title'])}, {c(patch['category'].upper())}, {c(group) if group else 0}, "
                        f"{c(warning) if warning else 0}, {name}, {len(edits)}}},")
        out.append(f"static const Patch patches_{index}[] = {{")
        out += rows
        out.append("};")
        firmwares.append(f"  {{{c(firmware['model'])}, {c(firmware['name'])}, {c(firmware['firmware'])}, patches_{index}, {len(rows)}}},")
    out.append("static const Firmware firmwares[] = {")
    out += firmwares
    out.append("};")
    (Path(__file__).parent / "patches_data.h").write_text("\n".join(out) + "\n")


main()
